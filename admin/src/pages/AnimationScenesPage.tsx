import React, { useMemo, useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import {
  Plus,
  Pencil,
  Trash2,
  Clapperboard,
  Eye,
  CheckCircle2,
  XCircle,
  Wand2,
  FileJson,
} from 'lucide-react';
import toast from 'react-hot-toast';
import { animationSceneAPI } from '../api/endpoints';
import { Badge } from '../components/ui/Badge';
import { EmptyState } from '../components/ui/EmptyState';
import { ConfirmDialog } from '../components/ui/ConfirmDialog';
import { SceneFormModal } from './animations/SceneFormModal';
import { ScenePreviewModal } from './animations/ScenePreviewModal';
import { CATEGORIES, CATEGORY_LABEL } from './animations/types';
import type { AnimationCategory, AnimationScene, AnimationSceneSummary } from '../types/animation';

export const AnimationScenesPage: React.FC = () => {
  const qc = useQueryClient();
  const [filter, setFilter] = useState<AnimationCategory | 'ALL'>('ALL');
  const [formOpen, setFormOpen] = useState(false);
  const [editing, setEditing] = useState<AnimationScene | null>(null);
  const [previewId, setPreviewId] = useState<string | null>(null);
  const [delTarget, setDelTarget] = useState<AnimationSceneSummary | null>(null);

  const { data, isLoading } = useQuery({
    queryKey: ['anim-scenes', filter],
    queryFn: () => animationSceneAPI.getAll(filter === 'ALL' ? undefined : filter),
  });
  const scenes: AnimationSceneSummary[] = data?.data?.data ?? [];

  const counts = useMemo(() => {
    const m: Record<string, number> = {};
    scenes.forEach((s) => {
      if (s.category) m[s.category] = (m[s.category] ?? 0) + 1;
    });
    return m;
  }, [scenes]);

  const publishMut = useMutation({
    mutationFn: ({ id, value }: { id: string; value: boolean }) =>
      animationSceneAPI.publish(id, value),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ['anim-scenes'] });
      toast.success('Publish status updated');
    },
    onError: () => toast.error('Failed to update publish status'),
  });

  const deleteMut = useMutation({
    mutationFn: () => animationSceneAPI.delete(delTarget!.id),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ['anim-scenes'] });
      toast.success('Scene deleted');
      setDelTarget(null);
    },
    onError: () => toast.error('Delete failed'),
  });

  const openCreate = () => {
    setEditing(null);
    setFormOpen(true);
  };

  const openEdit = async (id: string) => {
    try {
      const res = await animationSceneAPI.getById(id);
      setEditing(res.data?.data as AnimationScene);
      setFormOpen(true);
    } catch {
      toast.error('Could not load scene');
    }
  };

  const onSaved = () => {
    qc.invalidateQueries({ queryKey: ['anim-scenes'] });
    setFormOpen(false);
    setEditing(null);
  };

  return (
    <div className="p-8">
      {/* Header */}
      <div className="flex items-center justify-between mb-6">
        <div>
          <h1 className="text-2xl font-bold text-white flex items-center gap-2">
            <Clapperboard size={22} className="text-violet-400" />
            Canvas Animations
          </h1>
          <p className="text-slate-400 text-sm mt-1">
            Author time-based, interpolated scenes — generated by server simulators or hand-authored —
            across System Design, DSA, SQL, Concurrency &amp; AI/ML.
          </p>
        </div>
        <button
          onClick={openCreate}
          className="flex items-center gap-2 px-4 py-2.5 rounded-xl bg-gradient-to-r from-violet-600 to-indigo-600 hover:from-violet-500 hover:to-indigo-500 text-white text-sm font-medium transition shadow-lg shadow-violet-900/30"
        >
          <Plus size={16} />
          New Scene
        </button>
      </div>

      {/* Category filter */}
      <div className="flex flex-wrap gap-2 mb-5">
        <FilterChip
          label={`All (${scenes.length})`}
          active={filter === 'ALL'}
          onClick={() => setFilter('ALL')}
        />
        {CATEGORIES.map((c) => (
          <FilterChip
            key={c}
            label={`${CATEGORY_LABEL[c]}${counts[c] ? ` (${counts[c]})` : ''}`}
            active={filter === c}
            onClick={() => setFilter(c)}
          />
        ))}
      </div>

      {/* Table */}
      <div className="bg-surface/60 border border-white/8 rounded-2xl overflow-hidden">
        {isLoading ? (
          <div className="flex items-center justify-center h-40 text-slate-500 text-sm">Loading…</div>
        ) : scenes.length === 0 ? (
          <EmptyState
            message="No animation scenes yet"
            action={
              <button onClick={openCreate} className="text-xs text-violet-400 hover:underline">
                Create your first scene
              </button>
            }
          />
        ) : (
          <table className="w-full text-sm">
            <thead>
              <tr className="border-b border-white/8 text-xs text-slate-500 uppercase tracking-wider">
                <th className="text-left px-6 py-3">Title</th>
                <th className="text-left px-6 py-3">Category</th>
                <th className="text-left px-6 py-3">Source</th>
                <th className="text-left px-6 py-3">Frames / Dur</th>
                <th className="text-left px-6 py-3">Status</th>
                <th className="px-6 py-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody>
              {scenes.map((s, i) => (
                <tr
                  key={s.id}
                  className={`border-b border-white/5 hover:bg-white/3 transition ${
                    i % 2 === 0 ? '' : 'bg-white/[0.02]'
                  }`}
                >
                  <td className="px-6 py-4">
                    <div className="font-medium text-white">{s.title}</div>
                    <div className="text-xs text-slate-500">/{s.slug}</div>
                  </td>
                  <td className="px-6 py-4">
                    {s.category ? (
                      <Badge label={CATEGORY_LABEL[s.category]} />
                    ) : (
                      <span className="text-slate-600 text-xs">—</span>
                    )}
                  </td>
                  <td className="px-6 py-4">
                    <span className="inline-flex items-center gap-1.5 text-xs text-slate-300">
                      {s.source === 'GENERATED' ? (
                        <Wand2 size={13} className="text-violet-400" />
                      ) : (
                        <FileJson size={13} className="text-sky-400" />
                      )}
                      {s.source}
                      {s.kind && <code className="text-slate-500">· {s.kind}</code>}
                    </span>
                  </td>
                  <td className="px-6 py-4 text-slate-400 text-xs tabular-nums">
                    {s.keyframeCount ?? '—'} ·{' '}
                    {s.duration != null ? `${(s.duration / 1000).toFixed(1)}s` : '—'}
                  </td>
                  <td className="px-6 py-4">
                    <button
                      onClick={() => publishMut.mutate({ id: s.id, value: !s.isPublished })}
                      className={`inline-flex items-center gap-1.5 text-xs font-medium px-2.5 py-1 rounded-full transition ${
                        s.isPublished
                          ? 'bg-emerald-500/15 text-emerald-400 hover:bg-emerald-500/25'
                          : 'bg-slate-500/15 text-slate-400 hover:bg-slate-500/25'
                      }`}
                    >
                      {s.isPublished ? <CheckCircle2 size={12} /> : <XCircle size={12} />}
                      {s.isPublished ? 'Published' : 'Draft'}
                    </button>
                  </td>
                  <td className="px-6 py-4 flex justify-end gap-2">
                    <button
                      onClick={() => setPreviewId(s.id)}
                      className="p-1.5 rounded-lg text-slate-400 hover:text-violet-400 hover:bg-violet-500/10 transition"
                      title="Preview"
                    >
                      <Eye size={14} />
                    </button>
                    <button
                      onClick={() => openEdit(s.id)}
                      className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-white/10 transition"
                      title="Edit"
                    >
                      <Pencil size={14} />
                    </button>
                    <button
                      onClick={() => setDelTarget(s)}
                      className="p-1.5 rounded-lg text-slate-400 hover:text-rose-400 hover:bg-rose-500/10 transition"
                      title="Delete"
                    >
                      <Trash2 size={14} />
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>

      <SceneFormModal
        open={formOpen}
        editing={editing}
        onClose={() => {
          setFormOpen(false);
          setEditing(null);
        }}
        onSaved={onSaved}
      />

      <ScenePreviewModal sceneId={previewId} onClose={() => setPreviewId(null)} />

      <ConfirmDialog
        open={!!delTarget}
        message={`Delete scene "${delTarget?.title}"? This cannot be undone.`}
        onConfirm={() => deleteMut.mutate()}
        onCancel={() => setDelTarget(null)}
        loading={deleteMut.isPending}
      />
    </div>
  );
};

const FilterChip: React.FC<{ label: string; active: boolean; onClick: () => void }> = ({
  label,
  active,
  onClick,
}) => (
  <button
    onClick={onClick}
    className={`text-xs px-3 py-1.5 rounded-full border transition ${
      active
        ? 'bg-violet-600/20 text-violet-300 border-violet-500/40'
        : 'text-slate-400 border-white/10 hover:bg-white/5'
    }`}
  >
    {label}
  </button>
);
